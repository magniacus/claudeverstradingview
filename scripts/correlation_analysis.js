function dayKey(ts) { return Math.floor(ts / 86400); }

const goldMap = new Map(gold2026.map(d => [dayKey(d.t), d.c]));
const btcMap  = new Map(btc2026.map(d => [dayKey(d.t), d.c]));

// Trouver les jours communs (avec tolérance ±1 jour pour Gold/BTC décalage)
const aligned = [];
for (const [dk, btcC] of btcMap) {
  // Cherche Gold ce jour, ou le jour précédent/suivant
  const goldC = goldMap.get(dk) || goldMap.get(dk-1) || goldMap.get(dk+1);
  if (goldC) aligned.push({ dk, btc: btcC, gold: goldC });
}
aligned.sort((a, b) => a.dk - b.dk);

// Rendements logarithmiques
const btcReturns = [];
const goldReturns = [];
for (let i = 1; i < aligned.length; i++) {
  btcReturns.push(Math.log(aligned[i].btc / aligned[i-1].btc));
  goldReturns.push(Math.log(aligned[i].gold / aligned[i-1].gold));
}

// Pearson correlation
function pearson(x, y) {
  const n = x.length;
  const meanX = x.reduce((s, v) => s + v, 0) / n;
  const meanY = y.reduce((s, v) => s + v, 0) / n;
  let num = 0, denX = 0, denY = 0;
  for (let i = 0; i < n; i++) {
    num  += (x[i] - meanX) * (y[i] - meanY);
    denX += (x[i] - meanX) ** 2;
    denY += (y[i] - meanY) ** 2;
  }
  return num / Math.sqrt(denX * denY);
}

const r = pearson(btcReturns, goldReturns);

// Analyse par période (Q1 + Q2 2026 si suffisant de données)
function period(label, from, to) {
  const sub = aligned.filter(d => d.dk >= dayKey(from) && d.dk <= dayKey(to));
  if (sub.length < 5) return null;
  const bR = [], gR = [];
  for (let i = 1; i < sub.length; i++) {
    bR.push(Math.log(sub[i].btc / sub[i-1].btc));
    gR.push(Math.log(sub[i].gold / sub[i-1].gold));
  }
  return { label, n: bR.length, r: pearson(bR, gR) };
}

